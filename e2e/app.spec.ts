import { expect, test } from '@playwright/test'
import { example } from '../src/example'

test('mobile combined list, copy, review, edit, and clear', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Convert', exact: true })).toBeDisabled()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390)
  await page.evaluate(text => navigator.clipboard.writeText(text), example)
  await page.getByRole('button', { name: 'Paste', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Paste Staffing Needs' })).toHaveValue(example)
  await page.getByRole('button', { name: 'Convert', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Copy List', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.body.scrollHeight <= window.innerHeight)).toBe(true)
  const output = page.getByLabel('Formatted staffing list')
  await expect(output).toContainText('09/19 - AM, PM')
  await expect(output).toContainText('Parker')
  const text = await output.innerText()
  expect(text).toContain('CNA\n\nNiles')
  expect(text).toContain('\n\n\nNurse\n\nNiles')
  expect(text.indexOf('CNA')).toBeLessThan(text.indexOf('Nurse'))
  await expect(page.getByRole('button', { name: 'Nurse', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'CNA', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Copy List', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText().then(value => value.replace(/\r\n/g, '\n')))).toBe(text)
  await page.getByRole('button', { name: 'Edit input' }).click()
  await page.getByRole('textbox', { name: 'Paste Staffing Needs' }).fill('95th\nNurse\n9/12 - 1/1\n9/13 - ?')
  await page.getByRole('button', { name: 'Convert', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Needs Review (1)' })).toBeVisible()
  await expect(page.getByLabel('Formatted staffing list')).toContainText('09/12 - AM, PM')
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Paste Staffing Needs' })).toHaveValue('')
  await page.getByRole('button', { name: 'Open app information' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
})

test('cached app reopens offline and converts and copies without requests', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByText('Offline Ready', { exact: true })).toBeVisible({ timeout: 20000 })
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.close()
  await context.setOffline(true)
  const offlinePage = await context.newPage()
  await offlinePage.goto('/')
  await offlinePage.getByRole('textbox', { name: 'Paste Staffing Needs' }).fill('Niles\nCNA\n9/12 - 3/2/0 (Call first)')
  await offlinePage.getByRole('button', { name: 'Convert', exact: true }).click()
  await expect(offlinePage.getByLabel('Formatted staffing list')).toHaveText('CNA\n\nNiles Nursing & Rehabilitation Center\n09/12 - AM, PM (Call first)')
  await offlinePage.getByRole('button', { name: 'Copy List' }).click()
  expect(await offlinePage.evaluate(() => navigator.clipboard.readText().then(text => text.replace(/\r\n/g, '\n')))).toBe('CNA\n\nNiles Nursing & Rehabilitation Center\n09/12 - AM, PM (Call first)')
  expect(await offlinePage.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
})
